void applyLanguage (const juce::String& code)
{
    if (code == "de")
        juce::LocalisedStrings::setCurrentMappings (new juce::LocalisedStrings (juce::String::fromUTF8 (germanStrings), false));
    else
        juce::LocalisedStrings::setCurrentMappings (nullptr);
}
